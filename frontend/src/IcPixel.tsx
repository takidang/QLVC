export function IcPixel({ ten }: { ten: TenIc }) {
  const luoi = LUOI[ten]
  if (!luoi) return null
  return (
    <svg
      className="ic-pixel"
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden="true"
    >
      {luoi.flatMap((hang, y) =>
        [...hang].flatMap((c, x) =>
          c === '#' ? [<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} />] : [],
        ),
      )}
    </svg>
  )
}
